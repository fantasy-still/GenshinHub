"""End-to-end UI checks against ui_server.py. Never uses a real API key."""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright, expect

OUT=Path(__file__).resolve().parents[1]/'test-results';OUT.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(channel='msedge',headless=True)
    page=browser.new_page(viewport={'width':1440,'height':960},device_scale_factor=1)
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:18766/#token=ui-test-session')
    expect(page.locator('#settings')).to_be_visible()
    page.get_by_role('button',name='关闭设置',exact=True).click()
    expect(page.locator('.welcome h1')).to_be_visible()
    page.screenshot(path=str(OUT/'首页.png'),full_page=True)
    page.locator('#open-settings').click();page.locator('#api-key').fill('fake-key-for-ui-test-only')
    page.locator('#connect-key').click();expect(page.locator('#connection-result')).to_contain_text('已连接',timeout=10000)
    expect(page.locator('#review-answer')).not_to_be_checked()
    page.locator('#review-answer').check()
    page.locator('#preferences-form button[type="submit"]').click()
    assert page.locator('#api-key').input_value()==''
    page.get_by_role('button',name='关闭设置',exact=True).click()
    page.locator('#prompt').fill('丑角和海洛塔帝是什么关系？');page.locator('#prompt').press('Enter')
    thinking=page.locator('#messages details.reasoning').first
    expect(thinking).to_have_attribute('open','')
    expect(thinking.locator('pre')).to_contain_text('这是自动化界面测试')
    page.screenshot(path=str(OUT/'流式思考.png'),full_page=True)
    thinking.locator('summary').click()
    expect(thinking).not_to_have_attribute('open','')
    expect(thinking.locator('pre')).to_contain_text('继续核对上下文',timeout=5000)
    expect(thinking).not_to_have_attribute('open','')
    expect(page.locator('#messages .answer').last).to_contain_text('皮耶罗曾任',timeout=15000)
    expect(page.locator('#stop')).to_be_hidden()
    expect(page.locator('.draft-record')).to_have_count(2)
    expect(page.locator('.message-footer').last).to_contain_text('已进行证据复核')
    saved_thinking=page.locator('#messages details.reasoning').first
    saved_thinking.locator('summary').click()
    expect(saved_thinking.locator('pre')).to_contain_text('继续核对上下文')
    page.locator('.answer a[href^="kb:"]').last.click()
    expect(page.locator('#panel-body')).to_contain_text('副院长')
    page.screenshot(path=str(OUT/'回答与原文.png'),full_page=True)
    page.locator('#close-panel').click();page.locator('#open-memory').click()
    page.get_by_role('textbox',name='新的记忆').fill('优先解释人物动机。')
    page.get_by_role('button',name='保存记忆',exact=True).click()
    expect(page.locator('.memory-item')).to_contain_text('优先解释人物动机。')
    page.reload();expect(page.locator('#memory-count')).to_have_text('1')
    expect(page.locator('.chat-title')).to_have_count(1)
    page.locator('.chat-title').click();expect(page.locator('#messages .answer').last).to_contain_text('皮耶罗曾任')
    page.locator('#messages details.reasoning').first.locator('summary').click()
    expect(page.locator('#messages details.reasoning pre').first).to_contain_text('继续核对上下文')
    page.locator('#open-context').click();expect(page.locator('#panel-body')).to_contain_text('920')
    page.locator('#close-panel').click();page.locator('#new-chat').click()
    page.locator('#prompt').fill('停止测试');page.locator('#prompt').press('Enter')
    expect(page.locator('#messages .answer').last).to_contain_text('用于停止操作',timeout=10000)
    page.locator('#stop').click();expect(page.locator('#stop')).to_be_hidden(timeout=10000)
    expect(page.locator('.message-footer')).to_contain_text('已中断')
    page.locator('#open-settings').click();page.locator('#new-direct').click()
    page.locator('#prompt').fill('你好');page.locator('#prompt').press('Enter')
    expect(page.locator('#messages .answer').last).to_contain_text('原生模式',timeout=10000)
    expect(page.locator('#mode-label')).to_have_text('原生对话')
    page.locator('#search-library').click();page.get_by_role('textbox',name='资料检索词').fill('皮耶罗 副院长')
    page.get_by_role('button',name='搜索',exact=True).click();expect(page.locator('.search-hit').first).to_be_visible()
    page.locator('#close-panel').click()
    page.set_viewport_size({'width':390,'height':844});page.locator('#toggle-sidebar').click()
    expect(page.locator('#sidebar')).to_be_visible();page.locator('#close-sidebar').click()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.screenshot(path=str(OUT/'移动窄屏.png'),full_page=True)
    browser.close()
    result={'checks':['初次连接','主界面','流式思考自动展开','思考手动折叠保持','历史思考重新展开','流式回答','工具调用','来源跳转','保存记忆','刷新恢复','历史切换','上下文用量','停止并保存','原生模式','资料搜索','窄屏布局'],'console_errors':errors,'provider':'本地模拟接口，无真实API调用'}
    (OUT/'界面验收.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps(result,ensure_ascii=False))
    assert not errors
